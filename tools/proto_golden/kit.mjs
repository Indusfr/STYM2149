// Usage: node tools/proto_golden/kit.mjs YM2149_Prototype.html > tests/data/proto/kit.txt
import { loadPrototype } from './load.mjs';

const { Proc, KIT_BANKS } = loadPrototype(process.argv[2], 48000);
const names = Object.keys(KIT_BANKS);
const out = [];
out.push('# Generated by tools/proto_golden/kit.mjs from YM2149_Prototype.html (buildDrums, buildChipDrums).');
for (const name of names) {
  const p = new Proc();
  const kit = JSON.parse(JSON.stringify(KIT_BANKS[name]));
  p.msg({ type: 'kit', kit });
  out.push('bank ' + name);
  for (let s = 0; s < 8; s++) {
    const b = p.builtin[s];
    out.push('sample ' + s + ' ' + b.length + ' ' + Array.from(b, v => v.toString(16)).join(''));
  }
  for (const vbl of [50, 60, 70]) {
    p.patch.vbl = vbl;
    p.buildChipDrums();
    for (let s = 0; s < 8; s++) {
      const fr = p.chipDrums[s];
      out.push('chip ' + vbl + ' ' + s + ' ' + fr.length + ' ' +
        fr.map(f => [f.tp, f.np, f.tone, f.noise, f.vol].join(',')).join(' '));
    }
  }
}
process.stdout.write(out.join('\n') + '\n');
