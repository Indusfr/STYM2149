// Usage: node tools/proto_golden/engine.mjs YM2149_Prototype.html > tests/data/proto/engine.txt
import { loadPrototype } from './load.mjs';

const SR = 48000;
const { Proc, CHORDS } = loadPrototype(process.argv[2], SR);
const out = [];
const num = (x) => String(x);  // shortest representation that reads back the same double
out.push('# Generated by tools/proto_golden/engine.mjs from YM2149_Prototype.html (YMProc worklet, CHORDS).');

// Tone periods (noteToTP), with and without pitch bend.
{
  const p = new Proc();
  for (const bend of [0, 0.37, -1.5, 2]) {
    p.bend = bend;
    const tps = [];
    for (let n = 0; n < 128; n++) tps.push(p.noteToTP(n).TP);
    out.push('tp ' + num(bend) + ' ' + tps.join(' '));
  }
}

// Slide curves (slideShape): 13 curves, 4 seeds, t from 0 to 1 in steps of 1/40, plus a few irregular t;
// Custom table in float32 values (those of the plugin).
{
  const p = new Proc();
  const table = [];
  for (let i = 0; i < 32; i++) table.push(Math.fround(0.5 - 0.5 * Math.cos(Math.PI * Math.pow(i / 31, 1.3))));
  p.patch.slideTable = table;
  out.push('table ' + table.map(num).join(' '));
  const ts = [];
  for (let i = 0; i <= 40; i++) ts.push(i / 40);
  ts.push(0.0123, 0.333333, 0.77, 0.999, 1 / 3, 2 / 3);
  for (let k = 0; k <= 12; k++)
    for (const seed of [1, 0, 3735928559, 123456789]) {
      const vals = ts.map((t) => num(p.slideShape(t, k, { slideSeed: seed })));
      out.push('shape ' + k + ' ' + seed + ' ' + ts.map(num).join(',') + ' ' + vals.join(','));
    }
}

// Slide quantisation (slideQuant): Chromatic and Scale-locked, several scales and roots.
{
  const p = new Proc();
  const fs = [];
  for (let i = 0; i < 60; i++) fs.push(27.5 * Math.pow(2, i * 0.137));
  for (const [k, mask, root] of [[7, 0, 0], [8, 0, 0], [8, 0xAB5, 0], [8, 0xAB5, 3], [8, 0x295, 7],
                                 [8, 0x001, 0], [8, 0x801, 11], [11, 0xAB5, 0]]) {
    p.patch.scaleMask = mask;
    p.patch.scaleRoot = root;
    out.push('quant ' + k + ' ' + mask + ' ' + root + ' ' + fs.map(num).join(',') + ' ' +
      fs.map((f) => num(p.slideQuant(f, k))).join(','));
  }
}

// Chords (Chord… menu).
CHORDS.forEach(([name, n], i) => out.push('chord ' + i + ' ' + n.length + ' ' + n.join(' ') + ' ' + name));

// Arpeggio played on the keyboard (arpTick): notes produced by 40 steps, held notes in the order they were pressed.
{
  const cases = [];
  for (const mode of [0, 1, 2, 3, 4])
    for (const oct of [1, 2, 3]) cases.push({ mode, oct, held: [64, 60, 67] });
  cases.push({ mode: 2, oct: 1, held: [60] });
  cases.push({ mode: 2, oct: 2, held: [62] });
  cases.push({ mode: 3, oct: 2, held: [67, 55, 60, 72] });
  cases.push({ mode: 5, oct: 1, held: [64, 60, 67], table: [0, 3, 7, 12, -5], tlen: 5 });
  cases.push({ mode: 5, oct: 1, held: [48], table: [0, 0, 12, 7, 0, 19, -12, 5], tlen: 8 });
  for (const c of cases) {
    const p = new Proc();
    const notes = [];
    p.trigger = (n) => notes.push(n);
    p.killTag = () => {};
    const table = new Int8Array(16);
    (c.table || [0, 4, 7]).forEach((x, i) => { table[i] = x; });
    Object.assign(p.arp, { on: 1, mode: c.mode, oct: c.oct, table, tlen: c.tlen || 3, idx: -1, dir: 1 });
    p.heldList = c.held.slice();
    p.heldVel = {};
    for (let i = 0; i < 40; i++) p.arpTick();
    out.push('arp ' + c.mode + ' ' + c.oct + ' ' + (c.tlen || 3) + ' ' + Array.from(table).join(',') + ' ' +
      c.held.join(',') + ' ' + notes.join(','));
  }
}

// VBL frames of a voice played on the keyboard: effective period, 4-bit volume, ornament noise and timer
// frequency, read at each frame (one frame at the attack, then every SR / VBL samples).
{
  const base = { toneEn: 1, noiseEn: 0, effect: 0, sidRatio: 1, vol4: 13, vibDepth: 0, vibRate: 6,
    ornOn: 0, ornLen: 8, ornLoop: 1, ornRate: 1, ornTable: [0], ornNse: [0], ornVol: [15],
    atk: 0, dcy: 0, sus: 100, rel: 0, adsrChip: 0, EP: 400 };
  const cases = [
    { vbl: 50, note: 60, ornOn: 1, ornLen: 4, ornTable: [0, 12, 7, 3], ornNse: [1, 0, 0, 1], ornVol: [15, 12, 10, 8] },
    { vbl: 50, note: 57, ornOn: 1, ornLen: 5, ornLoop: 0, ornRate: 2, ornTable: [0, 4, 7, 12, -12],
      ornNse: [0, 0, 1, 0, 0], ornVol: [15, 15, 9, 6, 3] },
    { vbl: 60, note: 72, vibDepth: 40, vibRate: 6 },
    { vbl: 70, note: 45, vibDepth: 150, vibRate: 13, ornOn: 1, ornLen: 3, ornRate: 3, ornTable: [0, -7, 5],
      ornNse: [0, 1, 0], ornVol: [15, 7, 11] },
    { vbl: 50, note: 64, effect: 1, sidRatio: 2, vibDepth: 25, vibRate: 5 },
    { vbl: 50, note: 40, effect: 3, ornOn: 1, ornLen: 2, ornTable: [0, 7], ornNse: [0, 0], ornVol: [15, 15] },
    { vbl: 50, note: 62, atk: 37, dcy: 113, sus: 45, adsrChip: 1, vol4: 14 },
    { vbl: 60, note: 66, atk: 0, dcy: 251, sus: 20, adsrChip: 1, vibDepth: 30, vibRate: 7 },
  ];
  for (const c0 of cases) {
    const c = Object.assign({}, base, c0);
    const p = new Proc();
    p.patch.vbl = c.vbl;
    const ch = p.chans[0];
    Object.assign(ch, c, { enabled: 1, level: 1, ornTable: null, ornNse: null, ornVol: null });
    ch.ornTable = new Array(64).fill(0);
    ch.ornNse = new Array(64).fill(0);
    ch.ornVol = new Array(64).fill(15);
    c.ornTable.forEach((x, i) => { ch.ornTable[i] = x; });
    c.ornNse.forEach((x, i) => { ch.ornNse[i] = x; });
    c.ornVol.forEach((x, i) => { ch.ornVol[i] = x; });
    p.trigger(c.note, 127, 'man');
    const v = p.voices[0];
    const L = new Float32Array(1), R = new Float32Array(1);
    const frame = Math.max(1, Math.round(SR / c.vbl));
    const frames = [];
    for (let s = 0; s < frame * 40; s++) {
      p.process([], [[L, R]]);
      if (s % frame === 0) {
        const timer = (c.effect === 1 || c.effect === 3) ? num(v.timerFreq) : '0';
        frames.push([v.tpEff || v.TP, v.vol4, v.ornNoise ? 1 : 0, timer].join(':'));
      }
    }
    const keys = ['vbl', 'note', 'effect', 'sidRatio', 'vol4', 'vibDepth', 'vibRate', 'ornOn', 'ornLen', 'ornLoop',
      'ornRate', 'atk', 'dcy', 'sus', 'rel', 'adsrChip'];
    out.push('vbl ' + keys.map((k) => k + '=' + num(c[k])).join(' ') + ' ornTable=' + c.ornTable.join(',') +
      ' ornNse=' + c.ornNse.join(',') + ' ornVol=' + c.ornVol.join(',') + ' frames=' + frames.join(','));
  }
}

// Legato of a monophonic track (16 voices): linear slide of 45 ms at 16 × VBL, period at each step.
{
  for (const [from, to, vbl] of [[60, 67, 50], [72, 59, 50], [48, 50, 60]]) {
    const p = new Proc();
    p.patch.vbl = vbl;
    Object.assign(p.chans[0], { enabled: 1, level: 1, mono: 1 });
    p.trigger(from, 127, 'man');
    const L = new Float32Array(1), R = new Float32Array(1);
    for (let s = 0; s < 100; s++) p.process([], [[L, R]]);
    p.trigger(to, 127, 'man');
    const v = p.voices.find((x) => x.on && x.note === to);
    const tps = [];
    let left = v.glide;
    tps.push(v.glideN);
    for (let s = 0; s < SR && v.glide > 0; s++) {
      p.process([], [[L, R]]);
      if (v.glide !== left) { left = v.glide; tps.push(v.TP); }
    }
    out.push('glide ' + from + ' ' + to + ' ' + vbl + ' ' + tps.join(','));
  }
}

process.stdout.write(out.join('\n') + '\n');
