// STYM2149 — parity data of the voice engine: tone periods, slide curves and quantisation, chords, arpeggio
// played on the keyboard, VBL frames (ornament, vibrato, "Chip" ADSR, SID, Sync Buzzer) and legato slide, taken
// from the prototype's worklet.
