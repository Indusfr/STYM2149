//           > src/gemui/src/FontDataSmall.cpp
//
// The prototype only has the 8×16 font; the small texts of the Atari ST's GEM come from two other EmuTOS system
// fonts (Atari ST encoding):
//   - `bios/fnt_st_8x8.c`: the 8×8, normal GEM font in low and medium resolution;
//   - `bios/fnt_st_6x6.c`: the 6×6, SMALL font of the AES (names of the desktop icons; `aes/gemgraf.c` picks it
//     as the smallest height of the workstation).
// Each file describes the font as a GEM form: `dat_table` in big-endian 16-bit words (68000), `form_width` bytes
// per row, `form_height` rows, glyph n at column n × cell width (fixed-pitch fonts: the offset table of the 6×6,
// `bios/fnt_off_6x6.c`, is 6 × n); `top` gives the baseline (8×8: row 6 = bottom of the capitals, row 7 =
// descenders; 6×6: rows 4 and 5).
// Same 112 characters as FontData.cpp: ASCII 0x20-0x7E, then the GEM glyphs U+E001-U+E008, which are the
// characters 0x01-0x08 of the Atari ST encoding (up, down, right, left arrows, close box, size box, full box,
// check mark), then those of FALLBACK (raster.mjs, musical note, bullet; AZERTY and QWERTZ
// engravings of the keyboard drawing).
import { readFileSync } from 'node:fs';

import { FALLBACK } from './raster.mjs';

function load(path, cell, height, top) {
  const src = readFileSync(path, 'utf8');
  const field = (name) => {
    const m = src.match(new RegExp('(\\d+),\\s*/\\*\\s*(?:U?WORD)\\s+' + name + '\\b'));
    if (!m) throw new Error(path + ': missing field: ' + name);
    return Number(m[1]);
  };
  const formWidth = field('form_width');
  const formHeight = field('form_height');
  if (formHeight !== height || field('top') !== top || field('max_cell_width') !== cell) throw new Error(path + ': unexpected form');
  if (field('first_ade') !== 0 || field('last_ade') !== 255 || formWidth * 8 !== 256 * cell) throw new Error(path + ': unexpected table');
  if (!/F_MONOSPACE/.test(src)) throw new Error(path + ': proportional font');
  const table = src.slice(src.indexOf('dat_table['), src.indexOf('};', src.indexOf('dat_table[')));
  const words = [...table.matchAll(/0x([0-9a-fA-F]{4})/g)].map((m) => parseInt(m[1], 16));
  if (words.length !== (formWidth * formHeight) / 2) throw new Error(path + ': dat_table: ' + words.length + ' words');
  const bytes = words.flatMap((w) => [w >> 8, w & 0xff]);
  const bit = (r, x) => (bytes[r * formWidth + (x >> 3)] >> (7 - (x & 7))) & 1;
  // Rows of a character, left-aligned in a byte (bit 7 = column 0).
  return (code) => Array.from({ length: height }, (_, r) => {
    let v = 0;
    for (let i = 0; i < cell; ++i) v |= bit(r, code * cell + i) << (7 - i);
    return v;
  });
}

const fonts = [
  { name: 'k8x8', rows: 'k8x8Rows', glyphs: load(process.argv[2], 8, 8, 6), what: '8×8 font (bios/fnt_st_8x8.c)' },
  { name: 'k6x6', rows: 'k6x6Rows', glyphs: load(process.argv[3], 6, 6, 4), what: '6×6 font (bios/fnt_st_6x6.c)' },
];

const codes = [];
for (let c = 0x20; c <= 0x7e; ++c) codes.push({ code: c, label: c === 0x5c ? 'backslash' : JSON.stringify(String.fromCharCode(c)) });
const gem = ['up arrow', 'down arrow', 'right arrow', 'left arrow', 'close box', 'size box',
  'full box', 'check mark'];
gem.forEach((name, i) => codes.push({ code: 1 + i, label: 'U+E00' + (1 + i) + ' ' + name }));
for (const [c, atari] of FALLBACK)
  codes.push({ code: atari, label: 'U+' + c.toString(16).toUpperCase() + ' (Atari ST 0x' + atari.toString(16).toUpperCase().padStart(2, '0') + ')' });

const hex = (v) => '0x' + v.toString(16).padStart(2, '0');
const out = [];
out.push('// STYM2149 — gemui: GEM system fonts 8×8 and 6×6 (small texts). GENERATED FILE, do not edit.');
out.push('// Generated by tools/gemfont/emutos_small.mjs from EmuTOS\'s bios/fnt_st_8x8.c and bios/fnt_st_6x6.c.');
out.push('// EmuTOS glyphs (GPL v2 or later, emutos.github.io).');
out.push('#include "gemui/FontData.h"');
out.push('');
out.push('namespace stym::gemui::fontdata {');
out.push('');
out.push(`static_assert(kGlyphCount == ${codes.length});`);
for (const f of fonts) {
  out.push('');
  out.push(`// ${f.what}: rows from top to bottom, bit 7 = column 0.`);
  out.push(`const uint8_t ${f.name}[kGlyphCount][${f.rows}] = {`);
  for (const { code, label } of codes) out.push(`    {${f.glyphs(code).map(hex).join(', ')}},  // ${label}`);
  out.push('};');
}
out.push('');
out.push('}  // namespace stym::gemui::fontdata');
process.stdout.write(out.join('\n') + '\n');
