//
// Usage: node tools/gemfont/extract.mjs YM2149_Prototype.html emutos/bios/fnt_st_8x16.c > src/gemui/src/FontData.cpp
//        node tools/gemfont/extract.mjs --prototype YM2149_Prototype.html emutos/bios/fnt_st_8x16.c
//             > tools/gemshot/PrototypeFont.cpp
//
// The prototype draws all its text with this font (1024 units per em, ascent 832, descent 192, advance 512, square
// contours set on the grid of 64 units). The reference rendering is the browser's without antialiasing
// (-webkit-font-smoothing:none in the prototype; on Linux, monochrome FreeType), reproduced here:
// - the contour is shifted left by xMin - lsb, as TrueType engines do (phantom point pp1): the lsb values of the
//   hmtx table are all 0, so the ink of each glyph starts at the origin. The TrueType lost there the left side
//   bearings of EmuTOS: i, l, ".", ":" stuck to the left of their cell, M, W, K one column to the right of the
//   others. gemui keeps each glyph at its place in the EmuTOS cell (sixth DAW test, item 68), the contours of
//   bios/fnt_st_8x16.c not shifted; --prototype writes the placement of the TrueType, with which gemshot draws the
//   scenes compared with the prototype's screenshots;
// - a pixel is lit if its centre is inside the contour (non-zero rule); a centre on a vertical edge counts as
//   right of the shape, not left; on a horizontal edge, as below the shape, not above;
// - the baseline is set on a pixel edge (ascent rounded, half up);
// - the horizontal origin of a glyph is at a quarter pixel (Skia: position rounded to the nearest quarter): each
//   glyph is rasterised four times, contour shifted by 0, 1/4, 1/2 and 3/4 of a pixel. A set identical to a set
//   already written, shifted by a whole number of columns, is not repeated (at 16 px, the contours fall on the
//   pixel grid: a single set, shifted by one column for 1/2 and 3/4).
// Checked glyph by glyph against Chromium, from 8 to 16 px, at the four quarters (tools/gemfont/README.md).
// The FALLBACK characters (raster.mjs), missing from the TrueType, come from the EmuTOS 8×16 font it is taken from:
// the script first checks that the contours of that font give back the TrueType for each of its characters, at
// every size and at the four quarters.
import { CODES, FALLBACK, QUARTERS, SIZES, TTF_CODES, atariCode, emutos8x16, rasterizeAt } from './raster.mjs';
import { extractTtf, parseTtf } from './ttf.mjs';

const args = process.argv.slice(2);
const prototype = args[0] === '--prototype';
if (prototype) args.shift();
const font = parseTtf(extractTtf(args[0]));
const emutos = emutos8x16(args[1]);
for (const c of TTF_CODES) if (!font.cmap.has(c)) throw new Error('missing character: U+' + c.toString(16));
for (const c of FALLBACK.keys()) if (font.cmap.has(c)) throw new Error('already in the TrueType: U+' + c.toString(16));
for (const c of TTF_CODES)
  for (const size of SIZES)
    for (let q = 0; q < QUARTERS; q++) {
      const a = rasterizeAt(font, font.cmap.get(c), size, q / QUARTERS).rows;
      const b = rasterizeAt(font, emutos(atariCode(c)), size, q / QUARTERS).rows;
      if (a.join() !== b.join()) throw new Error(`EmuTOS and TrueType differ: U+${c.toString(16)}, ${size} px, ${q}/4`);
    }
// Prototype: the TrueType's glyphs, from the origin; gemui: the EmuTOS glyphs at their place in the cell.
const glyphOf = (c) =>
  prototype ? (FALLBACK.has(c) ? emutos(FALLBACK.get(c)) : font.cmap.get(c)) : emutos(atariCode(c));

const hex = (v) => '0x' + v.toString(16).padStart(4, '0');
const label = (c) =>
  c < 0x7f ? (c === 0x5c ? 'backslash' : JSON.stringify(String.fromCharCode(c))) : 'U+' + c.toString(16).toUpperCase() +
    (FALLBACK.has(c) ? ' (Atari ST 0x' + FALLBACK.get(c).toString(16).toUpperCase().padStart(2, '0') + ')' : '');
const out = [];
out.push(...(prototype ? [
  '// STYM2149 — gemshot: GEM 8x16 font placed as the prototype\'s TrueType draws it, every glyph from the origin',
  '// for the scenes compared with the prototype\'s screenshots. GENERATED FILE, do not edit.',
  '// Generated by tools/gemfont/extract.mjs --prototype from the prototype\'s TrueType font (YM2149_Prototype.html)',
  '// and, for the characters of its fallback font, from EmuTOS\'s bios/fnt_st_8x16.c.',
] : [
  '// STYM2149 — gemui: GEM 8x16 font as bitmaps, from 8 to 16 px. GENERATED FILE, do not edit.',
  '// Generated by tools/gemfont/extract.mjs from EmuTOS\'s bios/fnt_st_8x16.c, each glyph at its place in the cell',
  '// rasterised like the prototype\'s TrueType font (YM2149_Prototype.html), which it is checked against.',
]));
out.push('// Glyphs taken from EmuTOS (GPL v2 or later, emutos.github.io).');
out.push(prototype ? '#include "PrototypeFont.h"' : '#include "gemui/FontData.h"');
out.push('');
out.push(prototype ? 'namespace stym::gemui::fontdata::prototype {' : 'namespace stym::gemui::fontdata {');
out.push('');
out.push(`static_assert(kGlyphCount == ${CODES.length});`);
out.push('');
const sizes = [];
for (const size of SIZES) {
  const k = size / font.upem;
  const top = -Math.ceil(font.ascent * k), rows = Math.ceil(font.descent * k) - top;
  // Sets written: { quarter, rows }; each quarter points to a set, with a whole shift.
  const sets = [], refs = [];
  for (let q = 0; q < QUARTERS; q++) {
    const glyphs = CODES.map((c) => rasterizeAt(font, glyphOf(c), size, q / QUARTERS, !prototype).rows);
    let ref = null;
    for (const s of sets)
      for (let shift = 0; shift < 8 && !ref; shift++)
        if (s.glyphs.every((g, gi) => g.every((r, ri) => r >> shift === glyphs[gi][ri]))) ref = { q: s.q, shift };
    if (!ref) {
      sets.push({ q, glyphs });
      ref = { q, shift: 0 };
      const name = `kRows${size}q${q}`;
      out.push(`// ${size} px, origin at ${q}/4 pixel: ${rows} rows, from ${top} to ${top + rows - 1} around the baseline.`);
      out.push(`static const uint16_t ${name}[kGlyphCount][${rows}] = {`);
      glyphs.forEach((g, gi) => out.push(`    {${g.map(hex).join(', ')}},  // ${label(CODES[gi])}`));
      out.push('};');
      out.push('');
    }
    refs.push(ref);
  }
  sizes.push({ size, top, rows, refs });
}
if (!prototype) {
  out.push('// Code points of the characters taken from the fallback font, in the order of their indices (FALLBACK).');
  const codes = [...FALLBACK.keys()].map((c) => '0x' + c.toString(16).toUpperCase());
  out.push(`const char32_t kFallbackCodes[kFallbackCount] = {${codes.join(', ')}};`);
  out.push('');
}
out.push('const Size kSizes[kSizeCount] = {');
for (const { size, top, rows, refs } of sizes) {
  // Advance, ascent and descent in 1/64 pixel (exact: multiples of 1/64 at all these sizes).
  const adv64 = (font.advance(font.cmap.get(0x41)) * size * 64) / font.upem;
  const asc64 = (font.ascent * size * 64) / font.upem, desc64 = (font.descent * size * 64) / font.upem;
  for (const v of [adv64, asc64, desc64]) if (!Number.isInteger(v)) throw new Error('non-integer metric');
  const bits = refs.map((r) => `&kRows${size}q${r.q}[0][0]`).join(', ');
  const shifts = refs.map((r) => r.shift).join(', ');
  out.push(`    {${size}, ${adv64}, ${asc64}, ${desc64}, ${top}, ${rows}, {${bits}}, {${shifts}}},`);
}
out.push('};');
out.push('');
out.push(prototype ? '}  // namespace stym::gemui::fontdata::prototype' : '}  // namespace stym::gemui::fontdata');
process.stdout.write(out.join('\n') + '\n');
